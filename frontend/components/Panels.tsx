"use client";

import type { Analysis, AnomalyPoint, Dataset } from "@/lib/types";
import { compact, full, pct, shortDate, PERIOD_NAME } from "@/lib/format";
import styles from "./dashboard.module.css";

export function Ledger({ analysis }: { analysis: Analysis }) {
  const { kpis, forecast, frequency } = analysis;
  const period = PERIOD_NAME[frequency];
  const growth = kpis.trend.growth_pct;
  return (
    <dl className={styles.ledger}>
      <div>
        <dt>Total</dt>
        <dd>{compact(kpis.total)}</dd>
        <p>Average {compact(kpis.average)} per {period}</p>
      </div>
      <div>
        <dt>Latest {period}</dt>
        <dd>{compact(kpis.latest)}</dd>
        <p>
          {pct(kpis.change_vs_previous_pct)} vs previous
          {kpis.change_vs_last_season_pct !== null && <>, {pct(kpis.change_vs_last_season_pct)} vs last cycle</>}
        </p>
      </div>
      <div>
        <dt>Growth</dt>
        <dd data-tone={kpis.trend.direction}>{pct(growth)}</dd>
        <p>{kpis.trend.basis}</p>
      </div>
      {forecast && (
        <div>
          <dt>Next {forecast.horizon} {period}s</dt>
          <dd data-tone="forecast">{compact(forecast.expected_total)}</dd>
          <p>Forecast total</p>
        </div>
      )}
    </dl>
  );
}

export function MarginNotes({
  points,
  frequency,
  active,
  onSelect,
}: {
  points: AnomalyPoint[];
  frequency: "D" | "W" | "M";
  active: string | null;
  onSelect: (d: string | null) => void;
}) {
  const major = points.filter((p) => p.severity !== "low");
  const minor = points.filter((p) => p.severity === "low");

  if (points.length === 0) {
    return (
      <aside className={styles.margin} data-calm="true">
        <h2 className={styles.marginTitle}>Nothing unusual</h2>
        <p className={styles.muted}>Every period sits within its expected range once trend and seasonality are accounted for.</p>
      </aside>
    );
  }

  const note = (p: AnomalyPoint) => (
    <li key={p.date}>
      <button
        type="button"
        className={styles.note}
        aria-pressed={active === p.date}
        onClick={() => onSelect(active === p.date ? null : p.date)}
      >
        <span className={styles.noteDate}>{shortDate(p.date, frequency)}</span>
        <span className={styles.noteBody}>
          {p.direction === "spike" ? "Spike" : "Drop"} to {compact(p.actual)}, expected about {compact(p.expected)}
          <span className={styles.noteDev}> ({pct(p.deviation_pct, 0)})</span>
        </span>
      </button>
    </li>
  );

  return (
    <aside className={styles.margin} aria-label="Flagged anomalies">
      <h2 className={styles.marginTitle}>
        {major.length > 0 ? `${major.length} worth checking` : "Minor irregularities"}
      </h2>
      <ul className={styles.notes}>{(major.length ? major : minor).slice(0, 8).map(note)}</ul>
      {major.length > 0 && minor.length > 0 && (
        <details className={styles.minor}>
          <summary>{minor.length} minor</summary>
          <ul className={styles.notes}>{minor.slice(0, 12).map(note)}</ul>
        </details>
      )}
    </aside>
  );
}

export function Findings({ analysis }: { analysis: Analysis }) {
  const { insights } = analysis;
  return (
    <section className={styles.findings} aria-labelledby="findings-title">
      <h2 id="findings-title">What the numbers say</h2>
      <ul className={styles.findingList}>
        {insights.insights.map((t) => (
          <li key={t}>{t}</li>
        ))}
      </ul>
      {insights.actions.length > 0 && (
        <>
          <h3>Do next</h3>
          <ul className={styles.actionList}>
            {insights.actions.map((t) => (
              <li key={t}>{t}</li>
            ))}
          </ul>
        </>
      )}
      <p className={styles.footnote}>
        {insights.source === "llm"
          ? "Written by an AI model from the computed figures above; numbers are not generated by the model."
          : "Written from the computed figures by rule-based templates."}
      </p>
    </section>
  );
}

export function Movers({ analysis }: { analysis: Analysis }) {
  const movers = analysis.top_movers;
  if (!movers.length) return null;
  const period = PERIOD_NAME[analysis.frequency];
  const w = movers[0].window_periods;
  return (
    <section className={styles.tableSection} aria-labelledby="movers-title">
      <h2 id="movers-title">What drove the change</h2>
      <p className={styles.muted}>
        Last {w} {period}{w === 1 ? "" : "s"} compared with the {movers[0].compared_to}.
      </p>
      <div className={styles.tableWrap}>
        <table className={styles.table}>
          <thead>
            <tr>
              <th scope="col">Segment</th>
              <th scope="col">Now</th>
              <th scope="col">Before</th>
              <th scope="col">Change</th>
            </tr>
          </thead>
          <tbody>
            {movers.map((m) => (
              <tr key={m.category}>
                <th scope="row">{m.category}</th>
                <td>{compact(m.recent)}</td>
                <td>{compact(m.prior)}</td>
                <td data-tone={m.change >= 0 ? "up" : "down"}>
                  {m.change >= 0 ? "+" : "−"}
                  {compact(Math.abs(m.change))} <span className={styles.muted}>{pct(m.change_pct)}</span>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </section>
  );
}

export function ForecastQuality({ analysis }: { analysis: Analysis }) {
  const fc = analysis.forecast;
  if (!fc) return null;
  const period = PERIOD_NAME[analysis.frequency];
  return (
    <section className={styles.tableSection} aria-labelledby="fq-title">
      <h2 id="fq-title">How the forecast was chosen</h2>
      <p className={styles.muted}>
        Each model was trained without the last {fc.holdout_periods} {period}s, then scored on how well it predicted them.
        {fc.improvement_vs_baseline_pct !== null && fc.improvement_vs_baseline_pct > 0 && (
          <> The chosen model was {fc.improvement_vs_baseline_pct}% more accurate than repeating last cycle.</>
        )}
      </p>
      <div className={styles.tableWrap}>
        <table className={styles.table}>
          <thead>
            <tr>
              <th scope="col">Model</th>
              <th scope="col">Avg. error</th>
              <th scope="col">MAPE</th>
            </tr>
          </thead>
          <tbody>
            {fc.backtest.map((b) => (
              <tr key={b.model} aria-current={b.model === fc.model ? "true" : undefined}>
                <th scope="row">
                  {b.model}
                  {b.model === fc.model && <span className={styles.chosen}>chosen</span>}
                </th>
                {b.skipped ? (
                  <td colSpan={2} className={styles.muted}>Needs more history</td>
                ) : (
                  <>
                    <td>{full(b.mae)}</td>
                    <td>{b.mape === null || b.mape === undefined ? "–" : `${b.mape.toFixed(1)}%`}</td>
                  </>
                )}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </section>
  );
}

